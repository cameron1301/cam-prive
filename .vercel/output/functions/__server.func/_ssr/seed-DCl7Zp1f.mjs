function calendarCells(ym) {
	const [y, m] = ym.split("-").map(Number);
	const firstDow = new Date(Date.UTC(y, m - 1, 1)).getUTCDay();
	const count = new Date(Date.UTC(y, m, 0)).getUTCDate();
	const cells = [];
	for (let i = 0; i < firstDow; i++) {
		const iso = addDays(`${ym}-01`, i - firstDow);
		cells.push({
			iso,
			inMonth: false
		});
	}
	for (let d = 1; d <= count; d++) cells.push({
		iso: `${ym}-${String(d).padStart(2, "0")}`,
		inMonth: true
	});
	while (cells.length % 7 !== 0) {
		const last = cells[cells.length - 1].iso;
		cells.push({
			iso: addDays(last, 1),
			inMonth: false
		});
	}
	return cells;
}
async function fileToDataUrl(file) {
	const url = URL.createObjectURL(file);
	try {
		const img = await new Promise((resolve, reject) => {
			const el = new Image();
			el.onload = () => resolve(el);
			el.onerror = () => reject(/* @__PURE__ */ new Error("Could not read that photo."));
			el.src = url;
		});
		const scale = Math.min(1, 960 / img.width);
		const canvas = document.createElement("canvas");
		canvas.width = Math.max(1, Math.round(img.width * scale));
		canvas.height = Math.max(1, Math.round(img.height * scale));
		const ctx = canvas.getContext("2d");
		if (!ctx) throw new Error("Could not prepare that photo.");
		ctx.drawImage(img, 0, 0, canvas.width, canvas.height);
		return canvas.toDataURL("image/jpeg", .72);
	} finally {
		URL.revokeObjectURL(url);
	}
}
