function ownerExceptions(data, today, now = Date.now()) {
	const notes = [];
	const pending = data.reservations.filter((r) => r.status === "pending_approval");
	if (pending.length) notes.push(`${pending.length} additional stay${pending.length === 1 ? "" : "s"} waiting for approval.`);
	for (const i of data.incidents) if (!i.resolved && i.severity !== "minor") notes.push(`${i.severity === "urgent" ? "Urgent" : "Needs attention"}: ${i.description}`);
	for (const r of data.reservations) if (isOverdue(r, today, now)) notes.push(`Stay ended without checkout — ${personName(data, r.managerId)}.`);
	const upcoming = nextReservation(data, today);
	if (upcoming && upcoming.checkIn <= addDays(today, 1)) {
		const blocked = yachtStatus(data, today, now);
		if (blocked === "cleaning_required" || blocked === "cleaning" || blocked === "maintenance" || blocked === "attention") notes.push("A guest arrives soon and the yacht is not ready.");
	}
	const wash = data.maintenance.find((m) => m.kind === "exterior" && !m.completedAt);
	if (wash && wash.due < today) notes.push("Monthly exterior wash is overdue.");
	return notes;
}
