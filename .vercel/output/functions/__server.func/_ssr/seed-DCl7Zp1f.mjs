function statsBetween(data, from, to, slipMonths) {
	let occupied = 0;
	let complimentary = 0;
	let paidNights = 0;
	let revenue = 0;
	for (const r of data.reservations) {
		if (r.status !== "confirmed" && r.status !== "checked_out") continue;
		const nightsList = nightsOf(r.checkIn, r.nights).filter((n) => n >= from && n <= to);
		occupied += nightsList.length;
		const complimentaryCap = Math.min(r.nights, r.complimentaryApplied ?? (r.entitlementConsumed ? 1 : r.kind === "complimentary" ? r.nights : 0));
		const all = nightsOf(r.checkIn, r.nights);
		let paidInRange = 0;
		for (const iso of nightsList) if (all.indexOf(iso) < complimentaryCap) complimentary += 1;
		else {
			paidNights += 1;
			paidInRange += 1;
		}
		const paidTotal = r.nights - complimentaryCap;
		if (paidTotal > 0) revenue += Math.round(r.amount * (paidInRange / paidTotal));
	}
	const cleaning = data.expenses.filter((e) => e.kind === "cleaning" && e.date >= from && e.date <= to).reduce((s, e) => s + e.amount, 0);
	const maintenance = data.expenses.filter((e) => e.kind === "maintenance" && e.date >= from && e.date <= to).reduce((s, e) => s + e.amount, 0);
	const slip = data.config.slipMonthly * slipMonths;
	return {
		occupied,
		complimentary,
		paidNights,
		revenue,
		cleaning,
		maintenance,
		slip,
		net: revenue - cleaning - maintenance - slip
	};
}
